def _normalize(value: Any) -> Any:
    if isinstance(value, (datetime.datetime, datetime.date, datetime.time)):
        return value.isoformat()
    if isinstance(value, dict):
        return {key: _normalize(item) for key, item in value.items()}
    if isinstance(value, list):
        return [_normalize(item) for item in value]
    return value


def _encode_postgres_credentials(database_url: str) -> str:
    """Percent-encode URI credentials while preserving already-encoded values."""
    scheme, separator, remainder = database_url.partition("://")
    if not separator or "@" not in remainder:
        return database_url

    credentials, endpoint = remainder.rsplit("@", 1)
    username, separator, password = credentials.partition(":")
    if not separator:
        return database_url

    encoded_username = quote(unquote(username), safe="")
    encoded_password = quote(unquote(password), safe="")
    return f"{scheme}://{encoded_username}:{encoded_password}@{endpoint}"


def _cast_timestamp_parameters(sql: str) -> str:
    """Cast timestamp placeholders explicitly; psycopg binds Python strings as text."""
    insert_match = re.search(
        r'INSERT\s+INTO\s+"?\w+"?\s*\(([^)]*)\)\s*VALUES\s*\(([^)]*)\)',
        sql,
        re.IGNORECASE,
    )
    if insert_match:
        columns = [item.strip().strip('"') for item in insert_match.group(1).split(",")]
        values = insert_match.group(2).split(",")
        for index, column in enumerate(columns):
            if column in _TIMESTAMP_COLUMNS and index < len(values):
                values[index] = values[index].strip() + "::timestamp"
        sql = sql[:insert_match.start(2)] + ", ".join(values) + sql[insert_match.end(2):]

    timestamp_comparison = r'("(?:' + "|".join(_TIMESTAMP_COLUMNS) + r')")\s*(=|<>|>=|<=|>|<)\s*%s'
    return re.sub(
        timestamp_comparison,
        lambda match: f"{match.group(1)} {match.group(2)} %s::timestamp",
        sql,
        flags=re.IGNORECASE,
    )


class _Cursor:
    def __init__(
        self,
        cursor,
        *,
        inserted_id: Optional[int] = None,
        rowcount: Optional[int] = None,
        release: Optional[Callable[[bool], None]] = None,
    ):
        self._cursor = cursor
        self.lastrowid = inserted_id
        self.rowcount = rowcount if rowcount is not None else cursor.rowcount
        self._release = release
        self._released = False

    def _finish(self, discard: bool = False) -> None:
        if self._released:
            return
        self._released = True
        if self._cursor is not None:
            try:
                self._cursor.close()
            except Exception:
                discard = True
        if self._release is not None:
            self._release(discard)

    def fetchone(self):
        try:
            row = self._cursor.fetchone()
        except Exception:
            self._finish(discard=True)
            raise
        self._finish()
        return _normalize(row) if row is not None else None

    def fetchall(self):
        try:
            rows = self._cursor.fetchall()
        except Exception:
            self._finish(discard=True)
            raise
        self._finish()
        return [_normalize(row) for row in rows]


class _ConnectionProxy:
    def __init__(self, database: "PostgresDatabase"):
        self._database = database

    def commit(self) -> None:
        # Connections use autocommit; the SQLite-compatible call is intentional no-op.
        return None

    def executemany(self, sql: str, rows: list) -> None:
        connection = self._database._require_connection()
        try:
            cursor = connection.cursor()
            query = _cast_timestamp_parameters(sql.replace("?", "%s"))
            cursor.executemany(cast(LiteralString, query), rows)
            cursor.close()
        except Exception:
            self._database._release_connection(connection, discard=True)
            raise
        self._database._release_connection(connection)


class PostgresDatabase:
    """Bounded PostgreSQL connection pool implementing the shared database API."""

    def __init__(
        self,
        database_url: Optional[str] = None,
        *,
        database_url_env: str = "B_SUPABASE_DB_URL",
        password_env: str = "B_SUPABASE_DB_PASS",
        provider_name: str = "Supabase",
    ):
        self.database_url = database_url
        self.database_url_env = database_url_env
        self.password_env = password_env
        self.provider_name = provider_name
        self.tables: dict[str, Table] = {}
        self._pool = None
        self._pool_lock = threading.Lock()
        self._conn = _ConnectionProxy(self)

    def create(self, *tables: Table) -> None:
        for table in tables:
            existing = self.tables.get(table.name)
            if existing is not None:
                if existing.model is not table.model:
                    raise ValueError(f"The table name {table.name} is already registered to another model.")
                continue
            table._db = cast(Database, self)
            self.tables[table.name] = table

    def use(self, table: str) -> Table:
        if table not in self.tables:
            raise KeyError(f"Table {table} does not exist!")
        return self.tables[table]

    def _require_connection(self):
        database_url = self._resolve_database_url()
        if not database_url:
            raise RuntimeError(
                    f"{self.database_url_env} is required to start the {self.provider_name} backend."
            )
        if not database_url.startswith(("postgres://", "postgresql://")):
            raise RuntimeError(
                    f"{self.database_url_env} must be a PostgreSQL connection URI "
                    "beginning with postgresql://."
            )
        try:
            import psycopg
            from psycopg_pool import ConnectionPool
            from psycopg.rows import dict_row
        except ImportError as error:
            raise RuntimeError(
                "Install requirements.txt, including psycopg-pool, to use a PostgreSQL backend."
            ) from error

        with self._pool_lock:
            if self._pool is None:
                self._pool = ConnectionPool(
                    conninfo=_encode_postgres_credentials(database_url),
                    min_size=DB_POOL_MIN_SIZE,
                    max_size=DB_POOL_MAX_SIZE,
                    max_waiting=DB_POOL_MAX_WAITING,
                    timeout=DB_POOL_TIMEOUT_SECONDS,
                    kwargs={
                        "sslmode": "require",
                        "row_factory": dict_row,
                        "autocommit": True,
                        "keepalives": 1,
                        "keepalives_idle": 30,
                        "keepalives_interval": 10,
                        "keepalives_count": 5,
                    },
                    open=False,
                )
                self._pool.open(wait=True, timeout=DB_POOL_TIMEOUT_SECONDS)
            return self._pool.getconn(timeout=DB_POOL_TIMEOUT_SECONDS)

    def _release_connection(self, connection, *, discard: bool = False) -> None:
        pool = self._pool
        if pool is not None:
            if discard and not getattr(connection, "closed", True):
                connection.close()
            pool.putconn(connection)
        elif not getattr(connection, "closed", True):
            connection.close()

    def _resolve_database_url(self) -> Optional[str]:
        database_url = self.database_url or os.getenv(self.database_url_env)
        if database_url is None or "{pass}" not in database_url:
            return database_url

        password = os.getenv(self.password_env)
        if password is None:
            raise RuntimeError(
                f"{self.password_env} is required when {self.database_url_env} contains {{pass}}."
            )
        encoded_password = quote(password, safe="")
        return database_url.replace("[{pass}]", encoded_password).replace(
            "{pass}", encoded_password
        )

    def initialize(self) -> None:
        connection = self._require_connection()
        try:
            with connection.cursor() as cursor:
                cursor.execute("SELECT pg_advisory_lock(714928301)")
                cursor.execute(
                    "CREATE TABLE IF NOT EXISTS schema_migrations ("
                    "version INTEGER PRIMARY KEY, applied_at TIMESTAMP WITHOUT TIME ZONE "
                    "NOT NULL DEFAULT CURRENT_TIMESTAMP)"
                )
                cursor.execute(
                    "ALTER TABLE schema_migrations ENABLE ROW LEVEL SECURITY"
                )
                cursor.execute("SELECT COALESCE(MAX(version), 0) AS version FROM schema_migrations")
                row = cursor.fetchone()
                current_version = int(row["version"] if row else 0)
                if current_version < SCHEMA_VERSION:
                    for statement in SCHEMA_SQL:
                        cursor.execute(statement)
                    cursor.execute(
                        "INSERT INTO schema_migrations (version) VALUES (%s) "
                        "ON CONFLICT (version) DO NOTHING",
                        (SCHEMA_VERSION,),
                    )
                cursor.execute("SELECT pg_advisory_unlock(714928301)")
        except Exception:
            self._release_connection(connection, discard=True)
            raise
        self._release_connection(connection)

    def check(self) -> bool:
        connection = self._require_connection()
        try:
            with connection.cursor() as cursor:
                cursor.execute("SELECT 1")
                result = cursor.fetchone() is not None
        except Exception:
            self._release_connection(connection, discard=True)
            raise
        self._release_connection(connection)
        return result

    def _execute(self, sql: str, params: Optional[list] = None) -> _Cursor:
        translated = _cast_timestamp_parameters(sql.replace("?", "%s"))
        insert_match = re.match(r'\s*INSERT\s+INTO\s+"?(\w+)"?', translated, re.IGNORECASE)
        if insert_match and "RETURNING" not in translated.upper():
            translated += ' RETURNING "id"'
        is_read = translated.lstrip().upper().startswith(("SELECT", "WITH"))
        attempts = 2 if is_read else 1
        for attempt in range(attempts):
            connection = self._require_connection()
            cursor = None
            try:
                cursor = connection.cursor()
                cursor.execute(cast(LiteralString, translated), params or [])
                if insert_match and "RETURNING" in translated.upper():
                    returned = cursor.fetchone()
                    if returned is None:
                        raise RuntimeError("PostgreSQL insert returned no generated id.")
                    inserted_id = cast(dict[str, Any], returned)["id"]
                    rowcount = cursor.rowcount
                    cursor.close()
                    self._release_connection(connection)
                    return _Cursor(None, inserted_id=inserted_id, rowcount=rowcount)
                if cursor.description is None:
                    rowcount = cursor.rowcount
                    cursor.close()
                    self._release_connection(connection)
                    return _Cursor(None, rowcount=rowcount)
                return _Cursor(
                    cursor,
                    release=lambda discard: self._release_connection(
                        connection,
                        discard=discard,
                    ),
                )
            except Exception as error:
                if cursor is not None:
                    try:
                        cursor.close()
                    except Exception:
                        pass
                self._release_connection(connection, discard=True)
                if attempt + 1 < attempts and self._is_connection_error(error):
                    continue
                raise
        raise RuntimeError("Database read retry loop exited unexpectedly.")

    @staticmethod
    def _is_connection_error(error: Exception) -> bool:
        try:
            import psycopg
        except ImportError:
            return False
        return isinstance(error, (psycopg.OperationalError, psycopg.InterfaceError))

    def exists(self, table: str) -> bool:
        row = self._execute(
            "SELECT table_name FROM information_schema.tables "
            "WHERE table_schema = current_schema() AND table_name = ?",
            [table],
        ).fetchone()
        return row is not None

    def load(self, model: type, name: Optional[str] = None) -> Table:
        table = Table(model, name=name)
        if not self.exists(table.name):
            raise KeyError(f"Table {table.name} does not exist in the database")
        self.create(table)
        return table

    def close(self) -> None:
        if self._pool is not None:
            self._pool.close(timeout=DB_POOL_TIMEOUT_SECONDS)
            self._pool = None

def create_database(
    database_url_env: str,
    password_env: str,
    provider_name: str,
) -> PostgresDatabase:
    database = PostgresDatabase(
        database_url_env=database_url_env,
        password_env=password_env,
        provider_name=provider_name,
    )
    database.create(
        Table(User, name="users"),
        Table(Session, name="sessions"),
        Table(Profile, name="profiles"),
        Table(Post, name="posts"),
        Table(Chip, name="chips"),
        Table(Notification, name="notifications"),
    )
    return database


